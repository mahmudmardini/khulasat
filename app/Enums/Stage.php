<?php

declare(strict_types=1);

namespace App\Enums;

use App\Domain\Summary\JobState;
use App\Support\I18n\BodyStrings;
use App\Support\Model\Effort;
use App\Support\Render\CarouselDesign;

/**
 * The six model stages — `prompts/islamic/PROMPT-PACK.md` والمواصفة §6.
 *
 * **ستٌّ لا سبع.** المرحلة الرابعة (التحقّق) **لا نموذج فيها**: مطابقة نصّية
 * حتمية — CLAUDE.md §2 القاعدة الثالثة. فمن عدّها هنا فتح باباً لسؤال نموذجٍ
 * عن صحّة حديث، وهو بعينه ما بُني هذا المنتج ليمنعه.
 *
 * وقيمُ الأربع الأُولى **مطابقة لـ {@see JobState}** عمداً: مفتاحُ المرحلة
 * في `summary_jobs.cost_breakdown` هو قيمة الحالة، فلو اختلفا لاحتاج الأمر
 * جدول تحويلٍ بينهما، ولانقسمت الكلفة على مفتاحين لا يجتمعان.
 *
 * والمرحلتان الأخيرتان (بيانات الإخراج والكاروسيل) لا حالةَ لهما: تجريان
 * داخل `rendering` — المواصفة §5.
 *
 * @see prompts/islamic/PROMPT-PACK.md قسم القواعد العامة
 */
enum Stage: string
{
    /** ١ — تنظيف التفريغ. اقتصادية · خرجها نصّ لا JSON. */
    case Cleaning = 'cleaning';

    /** ٢ — استخراج البنية. **الفئة العليا**، ولا تحتمل جودة أدنى. */
    case ExtractingStructure = 'extracting_structure';

    /** ٣ — استخراج الشواهد. ينقل اللفظ كما ورد **ولا يصحّحه من حفظه**. */
    case ExtractingEvidence = 'extracting_evidence';

    /** ٥ — كتابة المتن. الفئة العليا بتفكير عالٍ · خرجها HTML. */
    case Writing = 'writing';

    /** ٦ — بيانات الإخراج. متوسطة. */
    case OutputMetadata = 'output_metadata';

    /** ٧ — نصّ الكاروسيل. متوسطة، وتُستدعى عند طلب الكاروسيل وحده. */
    case Carousel = 'carousel';

    /**
     * ٨ — اختبارُ الفهم، T-195. متوسطة، وتُستدعى عند طلب الاختبار وحده.
     *
     * تبني الأسئلة من `ContentObject` بعد حسم المراجعة، ولا تعيد قراءة
     * التفريغ — كالمرحلة ٧. **ولا تصلها ألفاظُ الشواهد لتنسخها**: خيارُ
     * الشاهد معرّفٌ يُملأ عند العرض من لفظ مصدره.
     */
    case Quiz = 'quiz';

    /**
     * **خارج الستّ** — استخراج بيانات المحاضرة من صورة ملصق (T-09ب).
     *
     * وليست من مراحل الخطّ: تجري **قبله** عند الإدخال، ولا تمسّ متن الملخّص
     * ولا شواهده. ومخرَجها بياناتٌ وصفية تُعرض على مدير المحتوى ليصحّحها،
     * فلا تُنشر شيئاً بذاتها.
     *
     * ولذلك **لا مكان لها في `prompts/<المجال>/PROMPT-PACK.md`** — تلك حزمةُ
     * الستّ التي تصنع المحتوى المنشور.
     */
    case LectureDetails = 'lecture_details';

    /**
     * **خارج الستّ كذلك** — ترجمة المخرَج، T-38.
     *
     * تجري **بعد** الخطّ لا فيه: تأخذ المتن المحقَّق وتُخرج ترجمتَه، فلا
     * تمسّ شاهداً ولا تُعيد تحقّقاً. والتحقّق يجري على العربيّ مرّةً واحدة
     * (معيار قبولٍ في T-38)، **ولا يُعاد لكلّ لغة**.
     *
     * ★★ **ولا تصلها ألفاظ الآيات ولا الأحاديث.** الآيةُ ترجمتُها معتمدةٌ
     * تُقرأ من `quran_translations`، والحديثُ يبقى بلفظه العربي ويُضاف إليه
     * **معنًى موسوم**. و{@see BodyStrings} هو الذي
     * يحرس ذلك: اللفظ لا يدخل جدولَ الترجمة أصلاً.
     *
     * وليست في `PROMPT-PACK.md` مع الستّ: تلك حزمةُ ما يصنع المحتوى، وهذه
     * تنقله بعد أن صُنع.
     */
    case Translating = 'translating';

    /**
     * **خارج الستّ كذلك** — قوالبُ كاروسيل الجهة، T-173.
     *
     * تجري **للجهة لا لملخّص**: مرّةً حين تطلب قوالب لهويتها، أو حين يعيد
     * المشرف توليدها. وتُخرج مواصفاتٍ من كتالوجٍ مغلق
     * ({@see CarouselDesign})، لا نصّاً يُنشر ولا HTML،
     * فلا تمسّ متناً ولا شاهداً.
     *
     * وتعليماتُها في `shared/`: الشكلُ لا يختلف باختلاف المجال. وللمشرف أن
     * يكتب لجهةٍ تعليماتٍ تحلّ محلّها (`tenants.carousel_design_prompt`).
     */
    case CarouselDesign = 'carousel_design';

    /**
     * أتختلف تعليمات هذه المرحلة باختلاف المجال؟
     *
     * **الستّ تختلف**: حزمةٌ لكل مجال في `prompts/<المجال>/PROMPT-PACK.md`.
     * وأمّا استخراج بيانات الملصق فواحدٌ في كلّ مجال — عنوانٌ وملقٍ وتاريخ،
     * لا فرق فيها بين درسٍ شرعي ومحاضرةٍ في الطبّ. فتُقرأ من `shared/`،
     * ولا تُنسخ ستّ مرّات لتتباعد.
     */
    public function isDomainSpecific(): bool
    {
        return ! in_array($this, [self::LectureDetails, self::Translating, self::CarouselDesign], true);
    }

    /**
     * **ولا `temperature()` هنا** — نُزعت في T-34.
     *
     * المعامل مهجورٌ على نماذج الجيل الحالي: ضبطُه بغير الافتراضي يُعيد 400،
     * و400 ممّا لا يُعاد عليه في §6-أ، فكان يُسقط كلّ مهمّة من أوّل نداء حقيقي.
     * وما كان يُطلب به من حتميةٍ وعمقٍ يُطلب اليوم بـ`model_config.thinking_level`،
     * يترجمه كلّ محوّل إلى معامل مزوّده — {@see Effort}.
     *
     * وقواعد PROMPT-PACK العامّة ما تزال تذكر درجات الحرارة، وتعديلُها ليس
     * لنا — CLAUDE.md §2 القاعدة الثانية. تُعرض على مالك المنتج.
     */

    /** أتُخرج المرحلة JSON يُتحقّق من مخطّطه؟ — المواصفة §6. */
    public function expectsJson(): bool
    {
        return match ($this) {
            // التنظيف نصّ عادي، ولا مخطّط له. **وكتابةُ المتن صارت كتلاً
            // في JSON** — T-43، بعد أن كانت HTML بلا مخطّطٍ يحرسها.
            self::Cleaning => false,
            default => true,
        };
    }

    /**
     * حالةُ المهمّة التي تجري فيها هذه المرحلة، إن كانت لها حالة.
     *
     * ومفتاحُ الكلفة في `cost_breakdown` يُشتقّ منها حين توجد، وإلا فمن
     * قيمة المرحلة نفسها.
     */
    public function jobState(): ?JobState
    {
        return JobState::tryFrom($this->value);
    }

    /** المفتاح الذي تُقيَّد به كلفةُ هذه المرحلة. */
    public function costKey(): string
    {
        return $this->jobState()?->value ?? $this->value;
    }
}
