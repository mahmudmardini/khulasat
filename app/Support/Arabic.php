<?php

declare(strict_types=1);

namespace App\Support;

use Normalizer;

/**
 * Arabic text normalization for deterministic evidence matching.
 *
 * هذه أهمّ دالة في المشروع. كلّ إخفاق مطابقة يعود إليها، لأنّ المطابقة
 * كلّها تجري على مخرَجها لا على النصّ الأصلي. ولذلك:
 *
 *   ١. هي **التنفيذ الوحيد** للتطبيع في المشروع. لا تُنسخ خطوة منها إلى
 *      ملفّ آخر — النسختان تتباعدان، ويصير الإخفاق غير قابل للتفسير.
 *   ٢. الخطوات بالترتيب المذكور في المواصفة §7-1 بالضبط. الترتيب مقصود:
 *      إزالة التشكيل قبل توحيد الحروف، وضغط المسافات في الآخر.
 *
 * @see khulasah-build-spec.md §7-1
 */
final class Arabic
{
    /**
     * محارف التشكيل — المواصفة §7-1 الخطوة ١، بعد توسيع T-03ب.
     *
     * المواصفة كانت تقف عند \x{0652}، فتبقى المدّة \x{0653} ظاهرةً على حرف
     * لا صورة مركّبة له («أُو۟لَٰٓئِكَ» ← «اول◌ٓيك»). ووُسّع المدى إلى نهاية
     * كتلة العلامات \x{065F}، وأُضيفت علامات التعظيم \x{0610}-\x{061A}
     * التي ترد في متون الحديث، وعلامات العربية الموسَّعة \x{08D3}-\x{08FF}.
     *
     * والمعيار: **ألّا يبقى في المخرَج محرفٌ غير متباعد واحد** — يفحصه اختبار.
     */
    private const DIACRITICS = '/[\x{0610}-\x{061A}\x{064B}-\x{065F}\x{0670}\x{06D6}-\x{06ED}\x{08D3}-\x{08FF}]/u';

    /** صور الألف التي تُردّ إلى ألف مجرّدة — الخطوة ٣. */
    private const ALEF_FORMS = '/[\x{0623}\x{0625}\x{0622}\x{0671}]/u';

    /** محارف اتجاه وتحكّم لا تُرى ولا تُنطق، وتُفسد المطابقة صامتةً. */
    private const INVISIBLES = '/[\x{200B}-\x{200F}\x{202A}-\x{202E}\x{2066}-\x{2069}\x{FEFF}]/u';

    /** كلّ ما يُعدّ فراغاً، ومنه المسافة غير الفاصلة التي لا يلتقطها \s. */
    private const SPACES = '/[\s\x{00A0}\x{1680}\x{2000}-\x{200A}\x{2028}\x{2029}\x{202F}\x{205F}\x{3000}]+/u';

    /** الأرقام العربية الهندية بترتيب قيمتها من الصفر. */
    private const ARABIC_INDIC = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

    private function __construct() {}

    /**
     * Render Latin digits as Arabic-Indic ones.
     *
     * الأرقام في النصّ العربي عربية هندية — مهارة khulasah وSCREENS.md.
     * ولا تُستعمل في الجداول والحقول، فتلك تُحاذى وتُقارن باللاتينية.
     */
    public static function toArabicIndicDigits(string|int $value): string
    {
        return str_replace(range('0', '9'), self::ARABIC_INDIC, (string) $value);
    }

    /**
     * Strip vowel marks and kashida, leaving the letters as written.
     *
     * الخطوات ٠ و١ و٢ من التطبيع وحدها: نصٌّ **يُقرأ** كما هو، وقد رُفع عنه
     * التشكيل. وهو عمود `text_plain` في مدوّنة الحديث وما يقابله في المصحف
     * — بين المشكَّل الذي يُنشر والمطبَّع الذي يُطابَق، ولا يصلح أحدهما مكانه.
     *
     * **وهي هنا لا في مستدعيها** — القاعدة الأولى في هذا الصنف: خطوة تطبيعٍ
     * تُنسخ إلى ملفّ آخر تتباعد نسختاها ويصير الإخفاق غير قابل للتفسير.
     */
    public static function stripDiacritics(string $text): string
    {
        // ٠. توحيد صورة يونيكود إلى NFC.
        //    أ قد تُكتب محرفاً واحداً (U+0623) أو ألفاً وهمزةً مركّبتين
        //    (U+0627 + U+0654). وهما في العين سواء، فلو تُركتا لفشلت
        //    الخطوة ٣ على المفكَّك ونجحت على المركَّب، فاختلف تطبيع
        //    نصّين متطابقين. هذه الخطوة ليست في المواصفة، وبدونها
        //    خطواتها الثماني غير موثوقة على مدخل مفكَّك.
        $text = Normalizer::normalize($text, Normalizer::FORM_C) ?: $text;

        // ١. إزالة التشكيل: الحركات والتنوين والشدّة والسكون والمدّة،
        //    والألف الخنجرية، وعلامات الضبط القرآني ورمز نهاية الآية،
        //    وعلامات التعظيم في متون الحديث.
        //    «مَنْ عَمِلَ» ← «من عمل»
        $text = preg_replace(self::DIACRITICS, '', $text) ?? $text;

        // ٢. إزالة التطويل، وهو زينة خطّية لا تغيّر الكلمة.
        //    «الحمــــد» ← «الحمد»
        return str_replace("\u{0640}", '', $text);
    }

    /**
     * Fold Arabic text to the single form used for all evidence matching.
     */
    public static function normalize(string $text): string
    {
        // ٠ و١ و٢ — NFC، ثمّ التشكيل، ثمّ التطويل.
        $text = self::stripDiacritics($text);

        // ٣. توحيد الألف: أ إ آ ٱ ← ا.
        //    المتكلّم يُهمل الهمزة والكاتب يُثبتها، فلا يُبنى عليها فرق.
        $text = preg_replace(self::ALEF_FORMS, "\u{0627}", $text) ?? $text;

        // ٤. توحيد الياء: ى ← ي. «موسى» ← «موسي»
        $text = str_replace("\u{0649}", "\u{064A}", $text);

        // ٥. توحيد التاء المربوطة: ة ← ه. «طيبة» ← «طيبه»
        $text = str_replace("\u{0629}", "\u{0647}", $text);

        // ٦. توحيد الهمزات المتّكئة: ؤ ← و، ئ ← ي.
        //    «مؤمن» ← «مومن»، «أئمة» ← «ايمه»
        $text = str_replace(["\u{0624}", "\u{0626}"], ["\u{0648}", "\u{064A}"], $text);

        // ٧. إزالة الترقيم وأقواس التنصيص القرآني ﴿ ﴾ « ».
        //    **تُستبدل بمسافة لا تُحذف.** ولو حُذفت لالتصقت الكلمتان في
        //    «قال:الحمد» فصارتا «قالالحمد»، ولما طابقت شيئاً أبداً.
        $text = preg_replace('/\p{P}/u', ' ', $text) ?? $text;

        // ٨. إزالة المحارف غير المرئية ثم ضغط الفراغ.
        //    علامات الاتجاه تأتي مع النسخ من المتصفّح ولا تُرى في المحرّر،
        //    فتُفشل المطابقة بلا أثر ظاهر يدلّ على السبب.
        $text = preg_replace(self::INVISIBLES, '', $text) ?? $text;
        $text = preg_replace(self::SPACES, ' ', $text) ?? $text;

        return trim($text);
    }
}
