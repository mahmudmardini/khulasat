<?php

declare(strict_types=1);

namespace App\Support\Hadith;

use App\Support\Arabic;

/**
 * The recurring narration formulas of the corpus — T-06ب، القرار الرابع.
 *
 * **صيغةُ الرواية ليست حديثاً.** «قال رسول الله صلى الله عليه وسلم» ترد في
 * آلاف صفوف المدوّنة، فتُطابَق بنسبة مئة بالمئة **وتُنشر حديثاً صحيحاً
 * بتخريجٍ كامل**. وقد وقع هذا فعلاً وقُيس (T-05ب).
 *
 * **ولا يفصل الطولُ بينهما**: «قال رسول الله صلى الله عليه وسلم» سبع كلمات،
 * و«المسلم من سلم المسلمون من لسانه ويده» سبع كلمات. الأولى صيغةٌ **مطّردة**
 * تتكرّر في كلّ الصفوف، والثانية **متنٌ** يخصّ حديثاً بعينه. ورفعُ حدّ
 * الكلمات إلى ثمانٍ يردّ الحديث ويُبقي الثغرة مفتوحةً لصيغةٍ من تسع.
 *
 * فالفاصل أن يُنزع المطّرد ويُنظر ما بقي: **إن لم يبقَ متنٌ فلا اقتباس**.
 *
 * @see khulasah-build-spec.md §7-3
 */
final class NarrationFormulas
{
    /**
     * أقلّ ما يبقى بعد نزع الصيغ ليُعدّ متناً.
     *
     * وثلاثٌ لأنّ «إنما الأعمال بالنيات» ثلاث كلمات وهو حديث تامّ.
     */
    private const MIN_MATN_WORDS = 3;

    /**
     * الصيغ المطّردة، مطبَّعةً كما تخرج من {@see Arabic::normalize}.
     *
     * **والأطول قبل الأقصر**، فتُنزع «قال رسول الله» كاملةً قبل أن تُنزع
     * «رسول الله» فتترك «قال» يتيمةً.
     *
     * **وليس فيها «قال» مفردةً ولا «يقول»**: كلتاهما ترد في المتون
     * («قال الله تعالى»)، ونزعُها يُنقص متناً حقيقياً فيُردّ اقتباسٌ صحيح.
     * والإفراط في النزع يردّ الصحيح، والتفريط يُمرّر الصيغة — والأولى أضرّ،
     * إذ الصيغةُ تقف عند حدّ الكلمات الستّ على أيّ حال.
     *
     * @var list<string>
     */
    private const FORMULAS = [
        'سمعت رسول الله صلي الله عليه وسلم',
        'قال رسول الله صلي الله عليه وسلم',
        'عن رسول الله صلي الله عليه وسلم',
        'ان رسول الله صلي الله عليه وسلم',
        'قال النبي صلي الله عليه وسلم',
        'عن النبي صلي الله عليه وسلم',
        'ان النبي صلي الله عليه وسلم',
        'صلي الله عليه وسلم',
        'عليه الصلاه والسلام',
        'سمعت رسول الله',
        'قال رسول الله',
        'عن رسول الله',
        'قال النبي',
        'عن النبي',
        'رضي الله عنهما',
        'رضي الله عنهم',
        'رضي الله عنها',
        'رضي الله عنه',
        'انبانا',
        'انباني',
        'اخبرنا',
        'اخبرني',
        'حدثنا',
        'حدثني',
    ];

    private function __construct() {}

    /**
     * ما بقي من النصّ بعد نزع الصيغ المطّردة.
     *
     * ويُستقبَل مطبَّعاً — فالمقارنة على المطبَّع وحده، وتطبيعُه هنا ثانيةً
     * لا يضرّ ويُغني المستدعي عن التذكّر.
     */
    public static function strip(string $text): string
    {
        $normalized = Arabic::normalize($text);

        foreach (self::FORMULAS as $formula) {
            $normalized = str_replace($formula, ' ', $normalized);
        }

        return trim((string) preg_replace('/\s+/u', ' ', $normalized));
    }

    /**
     * أهذا النصّ صيغةُ روايةٍ لا متن؟
     *
     * **يُفحص على المستخرَج لا على المصدر.** المصدر صفٌّ كامل بإسناده، وفيه
     * الصيغ بالضرورة. والسؤال عن الاقتباس: أفيه متنٌ يُنسب، أم هو ديباجةٌ
     * تصلح لكلّ حديث؟
     */
    public static function isFormulaic(string $text): bool
    {
        $residue = self::strip($text);

        if ($residue === '') {
            return true;
        }

        return count(explode(' ', $residue)) < self::MIN_MATN_WORDS;
    }
}
