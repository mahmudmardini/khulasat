<?php

declare(strict_types=1);

namespace App\Support\Render;

use App\Enums\SlideKind;
use App\Support\Quran\AyahText;

/**
 * كاروسيلُ العيّنة الذي تُعاين عليه القوالب — T-173.
 *
 * **ثابتٌ لا من ملخّصٍ حقيقي**: الجهةُ تختار قالبها قبل أن تملك ملخّصاً، ومقارنةُ
 * ثلاثة قوالب لا تصحّ إلّا على محتوى واحد. وأنواعُه الثمانية كلُّها حاضرة،
 * وشريحةُ المتن الطويل فيه عمداً: قالبٌ لا يسعها لا يصلح.
 *
 * ولا بيانات فيه: تسمياتٌ محايدة، وآيةٌ وحديثٌ بلفظ مصدريهما.
 */
final class SampleCarousel
{
    public static function deck(): SlideDeck
    {
        $ayah = AyahText::decorate(
            'مَنْ عَمِلَ صَالِحًا مِنْ ذَكَرٍ أَوْ أُنْثَىٰ وَهُوَ مُؤْمِنٌ فَلَنُحْيِيَنَّهُ حَيَاةً طَيِّبَةً',
            ['ayah_number' => 97, 'is_fragment' => true],
        );

        return new SlideDeck([
            new Slide(1, SlideKind::Cover, 'نموذج المعاينة', 'هكذا تظهر شرائح ملخّصاتكم على إنستغرام.'),
            new Slide(2, SlideKind::Ayah, 'الآية المفتاح', $ayah, 'النحل · ٩٧', true),
            new Slide(3, SlideKind::Concept, 'الفكرة', 'سطرٌ يشرح الفكرة الرئيسية في الدرس بجملةٍ أو جملتين.'),
            new Slide(4, SlideKind::Diagnosis, 'التشخيص', 'وصفٌ قصير للمشكلة التي يعالجها الدرس، كما يكتبه الملخّص.'),
            new Slide(5, SlideKind::Axis, 'المحور الأوّل', 'نصُّ المحور بطوله المعتاد: جملتان أو ثلاث تشرح المحور، وتربطه بما قبله، وتمهّد لما بعده في الدرس نفسه.'),
            new Slide(6, SlideKind::Comparison, 'مقارنة', 'الأوّل كذا، والثاني كذا، والفرق بينهما في كذا.'),
            new Slide(7, SlideKind::Evidence, 'شاهد', 'إِنَّمَا الْأَعْمَالُ بِالنِّيَّاتِ', 'البخاري · ١', true),
            new Slide(8, SlideKind::Closing, 'الخاتمة', 'سطرُ الختام.'),
        ]);
    }

    /**
     * كاروسيلُ الإجهاد: أطولُ ما تخرجه المرحلة السابعة في كلّ نوع — T-173.
     *
     * يُقاس عليه فيضُ القالب قبل أن يُعرض على الجهة. فالنصُّ الحرّ بسقفه
     * (أربعون كلمة)، والعنوانُ طويل، والآيةُ تامّة، والحديثُ من أطول ما يُنقل
     * على شريحة. **وكلُّ لفظٍ شرعيٍّ فيه بلفظ مصدره**، منقولٌ من عيّنات الاختبار
     * المحقَّقة لا مكتوبٌ باليد. ولا تُركَّب آيةٌ من موضعين ليطول النصّ: ذاك
     * من الشواهد المدسوسة نفسها.
     */
    public static function stress(): SlideDeck
    {
        $ayah = AyahText::decorate(
            'مَنْ عَمِلَ صَالِحًا مِنْ ذَكَرٍ أَوْ أُنْثَىٰ وَهُوَ مُؤْمِنٌ فَلَنُحْيِيَنَّهُ حَيَاةً طَيِّبَةً وَلَنَجْزِيَنَّهُمْ أَجْرَهُم بِأَحْسَنِ مَا كَانُوا يَعْمَلُونَ',
            ['ayah_number' => 97],
        );

        $free = 'نصٌّ حرٌّ بأقصى ما تكتبه المرحلة السابعة في شريحةٍ واحدة، يشرح فكرةً من الدرس ويربطها بما قبلها، '
            .'ثمّ يضرب لها مثلاً قريباً من حياة الناس، ويختم بسؤالٍ يدعو القارئ إلى العمل بما علم.';

        return new SlideDeck([
            new Slide(1, SlideKind::Cover, 'عنوانُ درسٍ طويل يمتدّ إلى سطرين أو ثلاثة كما تكتبه بعض الجهات', 'سطرٌ تحت العنوان يصف الدرس ويذكر موضوعه وسياقه في جملةٍ أطول من المعتاد.'),
            new Slide(2, SlideKind::Ayah, 'الآية المفتاح في هذا الدرس', $ayah, 'النحل · ٩٧', true),
            new Slide(3, SlideKind::Concept, 'الفكرة الرئيسية في سطرٍ طويل', $free),
            new Slide(4, SlideKind::Diagnosis, 'تشخيصُ المشكلة كما يراها الدرس', $free),
            new Slide(5, SlideKind::Axis, 'المحور الأوّل: عنوانٌ من عدّة كلمات', $free),
            new Slide(6, SlideKind::Comparison, 'مقارنةٌ بين حالين مختلفين', $free),
            new Slide(7, SlideKind::Evidence, 'شاهدٌ من السنّة', 'احفظ الله يحفظك، احفظ الله تجده تجاهك، إذا سألت فاسأل الله، وإذا استعنت فاستعن بالله، واعلم أن الأمة لو اجتمعت على أن ينفعوك بشيء لم ينفعوك إلا بشيء قد كتبه الله لك، ولو اجتمعوا على أن يضروك بشيء لم يضروك إلا بشيء قد كتبه الله عليك، رفعت الأقلام وجفت الصحف', 'الترمذي · ٢٥١٦', true),
            new Slide(8, SlideKind::Closing, 'خاتمةُ الدرس', 'سطرُ الختام في جملةٍ أطول قليلاً من المعتاد تدعو إلى العمل بما سمع.'),
        ]);
    }
}
