/**
 * علامةُ نهاية الآية «۝» ورقمُها بالعربية الهندية، كما يضعها
 * `AyahText::decorate` في الخادم. **ومكتوبةٌ بترميزها** لأنّ المكوّنات لا
 * تحمل حرفاً عربياً خارج تعليقاتها (`DesignSystemTest`).
 */
export const AYAH_MARK = /(\u06DD[\u0660-\u0669]+)/u;

/**
 * النصّ كما يُلصق في منشور — T-172، ومثيلُه في الخادم `AyahText::forPost`.
 *
 * **الرقمُ يبقى والعلامةُ تسقط**: «۝٥٦» تصير «٥٦»، فلا يُضمن لخطّ إنستغرام
 * أن يعرف «۝».
 */
export function forPost(text: string): string {
  return text.replace(/\u06DD([\u0660-\u0669]+)/gu, '$1');
}
