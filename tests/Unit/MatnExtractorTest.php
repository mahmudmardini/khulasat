<?php

declare(strict_types=1);

use App\Support\Hadith\MatnExtractor;

// T-53. **حتميٌّ نصّيٌّ بلا نموذج** — CLAUDE.md §2 القاعدة ٣، فالاختبار
// وحدةٌ خالصة بلا قاعدة بيانات ولا شبكة.

it('يقطع السند ويُبقي الصحابيّ حين يكون المطلعُ وصلاً إلى النبيّ ﷺ', function (): void {
    $text = 'حَدَّثَنَا عُبَيْدُ بْنُ أَسْبَاطٍ، حَدَّثَنِي أَبِي، عَنِ الأَعْمَشِ، '
        .'عَنْ أَبِي هُرَيْرَةَ، عَنِ النَّبِيِّ صلى الله عليه وسلم قَالَ " مَنْ نَفَّسَ ".';

    expect(MatnExtractor::extract($text))
        ->toBe('عَنْ أَبِي هُرَيْرَةَ، عَنِ النَّبِيِّ صلى الله عليه وسلم قَالَ " مَنْ نَفَّسَ ".');
});

// **ولا يُقحم تابعيّاً** حين يحمل مطلعُ المتن الصحابيَّ بنفسه.
it('لا يُبقي ما قبل المطلع إن كان المطلعُ يحمل الصحابيّ', function (): void {
    $text = 'حَدَّثَنَا آدَمُ، حَدَّثَنَا ابْنُ أَبِي ذِئْبٍ، عَنْ سَعِيدٍ الْمَقْبُرِيِّ، '
        .'عَنْ أَبِي هُرَيْرَةَ قَالَ قَالَ رَسُولُ اللَّهِ صلى الله عليه وسلم " لَنْ يُنَجِّيَ ".';

    expect(MatnExtractor::extract($text))
        ->toBe('عَنْ أَبِي هُرَيْرَةَ قَالَ قَالَ رَسُولُ اللَّهِ صلى الله عليه وسلم " لَنْ يُنَجِّيَ ".')
        ->not->toContain('الْمَقْبُرِيِّ');
});

// «أَخْبَرَنَا» تبقى همزتُها بعد نزع التشكيل ولا تبقى بعد التطبيع. وهذا ما
// أخفق أوّلاً فبقي سبعةُ آلاف سندٍ غيرَ مقطوع — **إخفاقاً صامتاً**.
it('يعرف صيغ التحمّل المهموزة كما يعرف غيرها', function (): void {
    $text = 'أَخْبَرَنَا عَمْرُو بْنُ عَلِيٍّ، قَالَ حَدَّثَنَا سَعِيدٌ، عَنْ نَافِعٍ، '
        .'عَنِ ابْنِ عُمَرَ، أَنَّ رَسُولَ اللَّهِ صلى الله عليه وسلم قَالَ " الْبَيِّعَانِ ".';

    expect(MatnExtractor::extract($text))->toStartWith('عَنِ ابْنِ عُمَرَ، أَنَّ رَسُولَ اللَّهِ');
});

it('يحذف المتابعات اللاحقة للمتن', function (): void {
    $text = 'حَدَّثَنَا مَحْمُودٌ، عَنْ جَرِيرٍ، أَنَّ رَسُولَ اللَّهِ صلى الله عليه وسلم قَالَ " كَذَا ". تَابَعَهُ يُونُسُ.';

    expect(MatnExtractor::extract($text))->not->toContain('تَابَعَهُ')
        ->and(MatnExtractor::extract($text))->toContain('" كَذَا "');
});

// **فواتُ قطعٍ أهونُ من قطعِ متن.** فما لم يُتيقَّن حدُّه يخرج كما دخل.
it('يترك النصّ كما هو حين لا مرساة', function (): void {
    $text = 'قال الحسن البصري رحمه الله: إذا رآك الشيطان مداوماً ملّك ورفضك.';

    expect(MatnExtractor::extract($text))->toBe($text);
});

it('يترك النصّ كما هو حين لا سند يتصدّره', function (): void {
    $text = 'وقال رجل من الأنصار، ثمّ ذكر النبيّ صلى الله عليه وسلم في حديثه.';

    expect(MatnExtractor::extract($text))->toBe($text);
});

it('يترك المتن المجرّد من السند أصلاً', function (): void {
    $text = 'قَالَ رَسُولُ اللَّهِ صلى الله عليه وسلم " إِنَّمَا الأَعْمَالُ بِالنِّيَّاتِ ".';

    expect(MatnExtractor::extract($text))->toBe($text);
});

it('لا يُرجع فراغاً من نصٍّ فيه كلام', function (): void {
    expect(MatnExtractor::extract(''))->toBe('')
        ->and(MatnExtractor::extract('   '))->toBe('');
});

/*
 * ═══ T-68 — حارسُ ما بعد القطع ═══
 *
 * **بلاغُ مالك المنتج بلقطة من قائمة التخريج**، وفيها ثالثٌ لم يُحسب في
 * T-53: لا متناً نظيفاً ولا نصّاً تامّاً، **بل صدراً مشوّهاً**. ونصٌّ مبتورٌ
 * يُنشر باسم جهةٍ شرعية أخطرُ من نصٍّ مطوَّل.
 */

// سندان متوازيان (`ح وحدثنا`) والمتنُ في الثاني: المرساةُ تقع في الأوّل،
// فيخرج «سَلَمَةَ عَنْ أَبِي هُرَيْرَةَ… وَحَدَّثَنَا أَبُو الْيَمَانِ».
it('يردّ النصّ كاملاً حين يبقى تحمّلٌ بعد القطع', function (): void {
    $text = 'حَدَّثَنَا آدَمُ، عَنْ أَبِي سَلَمَةَ، عَنْ أَبِي هُرَيْرَةَ، عَنِ النَّبِيِّ صلى الله عليه وسلم. '
        .'وَحَدَّثَنَا أَبُو الْيَمَانِ، قَالَ أَخْبَرَنَا شُعَيْبٌ، أَنَّ أَبَا هُرَيْرَةَ قَالَ " كَذَا ".';

    // يُردّ كما دخل: فواتُ قطعٍ لا تشويهُ صدر.
    expect(MatnExtractor::extract($text))->toBe($text);
});

// صدرٌ متدلٍّ من صيغة تحمّلٍ في الحلقة السابقة — وكان يخرج «يَقُولُ سَمِعْتُ…».
it('ينزع الصدر المتدلّي ويبدأ بالسماع', function (): void {
    $text = 'حَدَّثَنَا مُسَدَّدٌ، عَنْ جَرِيرٍ، قَالَ سَمِعْتُ الْحَسَنَ، '
        .'يَقُولُ سَمِعْتُ رَسُولَ اللَّهِ صلى الله عليه وسلم يَقُولُ " كَذَا ".';

    expect(MatnExtractor::extract($text))
        ->toStartWith('سَمِعْتُ رَسُولَ اللَّهِ')
        ->not->toStartWith('يَقُولُ');
});

// **ولا يُنزع الصدرُ إن لم يكن متدلّياً**: «قال سمعت» في متنٍ صحابيٍّ يَبقى.
it('لا ينزع صدراً ليس متدلّياً', function (): void {
    $matn = 'عَنْ أَبِي هُرَيْرَةَ، قَالَ قَالَ رَسُولُ اللَّهِ صلى الله عليه وسلم " كَذَا ".';

    expect(MatnExtractor::extract('حَدَّثَنَا آدَمُ، '.$matn))->toBe($matn);
});

/*
 * ═══ T-116 — بلاغُ مالك المنتج بأربع لقطاتٍ من المهمّة ٤٩ ═══
 *
 * **وكلُّ نصٍّ هنا صفٌّ من المدوّنة بعينه**، لا مثالاً مصنوعاً: هذه هي
 * الصفوفُ التي خرجت بأسانيدها إلى صفحةٍ رآها المالك، فتُحفظ بأسمائها.
 */

// ١. سندان متوازيان: المرساةُ في الأوّل والمتنُ في الثاني — البخاري ٩٠٨.
it('يبلغ المتنَ في السند الثاني حين تقع المرساةُ في الأوّل', function (): void {
    $text = 'حَدَّثَنَا آدَمُ، قَالَ حَدَّثَنَا ابْنُ أَبِي ذِئْبٍ، قَالَ الزُّهْرِيُّ عَنْ سَعِيدٍ، '
        .'وَأَبِي، سَلَمَةَ عَنْ أَبِي هُرَيْرَةَ ـ رضى الله عنه ـ عَنِ النَّبِيِّ صلى الله عليه وسلم. '
        .'وَحَدَّثَنَا أَبُو الْيَمَانِ، قَالَ أَخْبَرَنَا شُعَيْبٌ، عَنِ الزُّهْرِيِّ، '
        .'قَالَ أَخْبَرَنِي أَبُو سَلَمَةَ بْنُ عَبْدِ الرَّحْمَنِ، أَنَّ أَبَا هُرَيْرَةَ، '
        .'قَالَ سَمِعْتُ رَسُولَ اللَّهِ صلى الله عليه وسلم يَقُولُ " إِذَا أُقِيمَتِ الصَّلاَةُ فَلاَ تَأْتُوهَا تَسْعَوْنَ ".';

    expect(MatnExtractor::extract($text))
        ->toBe('سَمِعْتُ رَسُولَ اللَّهِ صلى الله عليه وسلم يَقُولُ " إِذَا أُقِيمَتِ الصَّلاَةُ فَلاَ تَأْتُوهَا تَسْعَوْنَ ".')
        ->not->toContain('أَبُو الْيَمَانِ');
});

// ٢. صفٌّ بلا مرساةٍ أصلاً — البخاري ٦٥٧٠. «يا رسول الله» و«بشفاعتي»،
//    ولا «صلى الله عليه وسلم» في الصفّ كلِّه.
it('يقطع الإسنادَ المحضَ حين لا مرساة في الصفّ', function (): void {
    $text = 'حَدَّثَنَا قُتَيْبَةُ بْنُ سَعِيدٍ، حَدَّثَنَا إِسْمَاعِيلُ بْنُ جَعْفَرٍ، عَنْ عَمْرٍو، '
        .'عَنْ سَعِيدِ بْنِ أَبِي سَعِيدٍ الْمَقْبُرِيِّ، عَنْ أَبِي هُرَيْرَةَ ـ رضى الله عنه ـ '
        .'أَنَّهُ قَالَ قُلْتُ يَا رَسُولَ اللَّهِ مَنْ أَسْعَدُ النَّاسِ بِشَفَاعَتِكَ يَوْمَ الْقِيَامَةِ.';

    expect(MatnExtractor::extract($text))
        ->toStartWith('عَنْ أَبِي هُرَيْرَةَ')
        ->not->toContain('قُتَيْبَةُ')
        ->not->toContain('الْمَقْبُرِيِّ');
});

// ٣. ذيلُ المصنّف بعد المتن — البخاري ١٠. وفيه «حدّثنا» فكان يُوقع الحارس.
it('يقطع ذيلَ المصنّف وما فيه من طرقٍ أخرى', function (): void {
    $text = 'حَدَّثَنَا آدَمُ بْنُ أَبِي إِيَاسٍ، قَالَ حَدَّثَنَا شُعْبَةُ، عَنِ الشَّعْبِيِّ، '
        .'عَنْ عَبْدِ اللَّهِ بْنِ عَمْرٍو ـ رضى الله عنهما ـ عَنِ النَّبِيِّ صلى الله عليه وسلم '
        .'قَالَ " الْمُسْلِمُ مَنْ سَلِمَ الْمُسْلِمُونَ مِنْ لِسَانِهِ وَيَدِهِ ". '
        .'قَالَ أَبُو عَبْدِ اللَّهِ وَقَالَ أَبُو مُعَاوِيَةَ حَدَّثَنَا دَاوُدُ عَنْ عَامِرٍ.';

    expect(MatnExtractor::extract($text))
        ->toBe('عَنْ عَبْدِ اللَّهِ بْنِ عَمْرٍو ـ رضى الله عنهما ـ عَنِ النَّبِيِّ صلى الله عليه وسلم '
            .'قَالَ " الْمُسْلِمُ مَنْ سَلِمَ الْمُسْلِمُونَ مِنْ لِسَانِهِ وَيَدِهِ ".');
});

// وحكمُ الترمذيّ على حديثه ليس من حديثه — وهي ٣١٢٥ موضعاً في المدوّنة.
it('يقطع حكمَ الترمذيّ من آخر المتن', function (): void {
    $text = 'حَدَّثَنَا ابْنُ أَبِي عُمَرَ، عَنْ أَبِي وَائِلٍ، عَنْ مُعَاذِ بْنِ جَبَلٍ، '
        .'قَالَ كُنْتُ مَعَ النَّبِيِّ صلى الله عليه وسلم فِي سَفَرٍ. '
        .'قَالَ أَبُو عِيسَى هَذَا حَدِيثٌ حَسَنٌ صَحِيحٌ .';

    expect(MatnExtractor::extract($text))
        ->toBe('عَنْ مُعَاذِ بْنِ جَبَلٍ، قَالَ كُنْتُ مَعَ النَّبِيِّ صلى الله عليه وسلم فِي سَفَرٍ.');
});

// ٤. **والحارسُ كان يُخطئ** — الترمذي ٢٦١٦: «أَخْبِرْنِي» من كلام معاذٍ
//    للنبيّ ﷺ، تُطبَّع «اخبرني» فتُقرأ صيغةَ تحمّل، فيُردّ الحديثُ بإسناده.
it('لا يعدّ صيغةَ تحمّلٍ ما وقع منها في وسط الكلام', function (): void {
    $text = 'حَدَّثَنَا ابْنُ أَبِي عُمَرَ، عَنْ مَعْمَرٍ، عَنْ مُعَاذِ بْنِ جَبَلٍ، '
        .'قَالَ كُنْتُ مَعَ النَّبِيِّ صلى الله عليه وسلم فِي سَفَرٍ فَقُلْتُ '
        .'يَا رَسُولَ اللَّهِ أَخْبِرْنِي بِعَمَلٍ يُدْخِلُنِي الْجَنَّةَ.';

    expect(MatnExtractor::extract($text))
        ->toStartWith('عَنْ مُعَاذِ بْنِ جَبَلٍ')
        ->toContain('أَخْبِرْنِي بِعَمَلٍ')
        ->not->toContain('مَعْمَرٍ');
});

// ٥. T-78 — المتنُ يبدأ **داخل** مقطع المرساة بعد «حَدَّثَنِي ابْنُ عَبَّاسٍ».
//    ويبقى الصحابيُّ بلا اختراع: تُقطع الصيغةُ ويبقى اسمُه بعدها.
it('يقطع داخل مقطع المرساة ويُبقي الصحابيّ', function (): void {
    $text = 'حَدَّثَنَا سَعِيدُ بْنُ أَبِي مَرْيَمَ، حَدَّثَنِي عَمْرُو بْنُ أَبِي عَمْرٍو، '
        .'مَوْلَى الْمُطَّلِبِ أَخْبَرَنِي سَعِيدُ بْنُ جُبَيْرٍ، '
        .'مَوْلَى وَالِبَةَ الْكُوفِيُّ حَدَّثَنِي ابْنُ عَبَّاسٍ ـ رضى الله عنهما ـ '
        .'أَنَّهُ دَفَعَ مَعَ النَّبِيِّ صلى الله عليه وسلم يَوْمَ عَرَفَةَ.';

    expect(MatnExtractor::extract($text))
        ->toBe('ابْنُ عَبَّاسٍ ـ رضى الله عنهما ـ أَنَّهُ دَفَعَ مَعَ النَّبِيِّ صلى الله عليه وسلم يَوْمَ عَرَفَةَ.')
        ->not->toContain('الْكُوفِيُّ');
});

// **وذيلُ المصنّف لا يُقطع بالكنية وحدها** — أبو داود ٤٩٧٢: «أَبُو عَبْدِ
// اللَّهِ» رجلٌ في المتن يُخاطبه أبو مسعود، لا صاحبَ الكتاب.
it('لا يقطع كنيةَ مصنّفٍ وقعت في وسط المتن', function (): void {
    $text = 'حَدَّثَنَا مُسَدَّدٌ، عَنْ أَبِي قِلاَبَةَ، عَنْ أَبِي هُرَيْرَةَ، '
        .'عَنِ النَّبِيِّ صلى الله عليه وسلم أَنَّ أَبَا مَسْعُودٍ سَأَلَ '
        .'أَوْ قَالَ أَبُو عَبْدِ اللَّهِ لأَبِي مَسْعُودٍ مَا سَمِعْتَ فِي " زَعَمُوا ".';

    expect(MatnExtractor::extract($text))
        ->toContain('أَبُو عَبْدِ اللَّهِ')
        ->toContain('زَعَمُوا');
});

// **وصفُّ الإحالة لا متنَ له**: «مِثْلَهُ» تحيل على ما قبلها في الكتاب.
// فقطعُ إسنادها يُخرج كلمةً شاهداً — وتُردّ كاملةً كما كانت.
it('يردّ صفَّ الإحالة كاملاً ولا يُخرج منه كلمةً شاهداً', function (): void {
    $text = 'حَدَّثَنَا يَحْيَى بْنُ مُوسَى، حَدَّثَنَا مُحَمَّدُ بْنُ أَبِي مَعْشَرٍ، مِثْلَهُ .';

    expect(MatnExtractor::extract($text))->toBe($text);
});
